// Supabase with server access (v0.31.0). Rows through PostgREST (<project>.supabase.co/rest/v1) with the
// service_role / secret key, which bypasses Row Level Security, so it stays on Colon's server. Schema changes (create
// table, add column, any SQL) need the optional personal access token: the Management API's
// POST api.supabase.com/v1/projects/<ref>/database/query. Without it Colon says so instead of guessing.
const { must } = require('./http');

const IDENT = /^[a-z_][a-z0-9_]{0,62}$/i;
const OPS = ['eq', 'neq', 'gt', 'gte', 'lt', 'lte', 'like', 'ilike', 'is', 'in'];
const TYPES = new RegExp('^(text|varchar(\\(\\d{1,5}\\))?|int2|int4|int8|integer|bigint|smallint|numeric|real|float8|'
  + 'double precision|boolean|bool|date|timestamptz|timestamp|time|uuid|jsonb|json)$', 'i');
const ID = 'bigint generated by default as identity primary key';
const err = (status, code, message) => Object.assign(new Error(message), { status, code });
const ident = (v, what = 'table') => {
  if (!IDENT.test(String(v || ''))) {
    throw err(422, 'invalid', `“${String(v).slice(0, 40)}” isn’t a valid ${what} name.`);
  }
  return String(v);
};
const lit = (v) => (v === null ? 'null' : typeof v === 'object' ? JSON.stringify(v) : String(v));

// { status: 'paid', total: { gt: 100 }, id: { in: [1, 2] } } -> URLSearchParams entries
function filters(where = {}) {
  const out = [];
  for (const [k, v] of Object.entries(where || {})) {
    ident(k, 'column');
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      for (const [op, x] of Object.entries(v)) {
        if (!OPS.includes(op)) throw err(422, 'invalid', `Unknown filter “${op}”.`);
        out.push([k, op === 'in' ? `in.(${[].concat(x).map((y) => `"${String(y).replace(/"/g, '')}"`).join(',')})`
          : `${op}.${lit(x)}`]);
      }
    } else out.push([k, v === null ? 'is.null' : `eq.${lit(v)}`]);
  }
  return out;
}
function column(c) {
  const name = ident(c && c.name, 'column'), type = String((c && c.type) || 'text').trim();
  if (type === ID || (c && c.identity)) return `"${name}" ${ID}`;
  if (!TYPES.test(type)) throw err(422, 'invalid', `Column type “${type.slice(0, 30)}” isn’t supported.`);
  return `"${name}" ${type}${c.primary ? ' primary key' : ''}${c.required ? ' not null' : ''}`;
}

function supabase({ config, secret }, http) {
  const base = String(config.url || '').replace(/\/+$/, '');
  const host = (() => { try { return new URL(base).hostname; } catch { return ''; } })();
  if (!/^[a-z0-9]{10,40}\.supabase\.(co|in)$/.test(host)) {
    throw err(422, 'invalid', 'Server access works with a hosted Supabase project URL (https://<ref>.supabase.co).');
  }
  const ref = host.split('.')[0], key = secret.serviceKey;
  const headers = { apikey: key, ...(/^eyJ/.test(key) ? { authorization: `Bearer ${key}` } : {}) };
  const label = 'Supabase';
  const rest = (path, o = {}) => http.call(`${base}/rest/v1/${path}`, { ...o, headers: { ...headers, ...(o.headers
    || {}) }, label });
  const qs = (pairs) => pairs.map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(v)}`).join('&');

  async function sql(query) {
    if (!secret.accessToken) {
      throw err(409, 'no_sql', 'Creating or changing Supabase tables needs a personal access token (sbp_…). Add it '
        + 'in Data → Supabase → Edit, or create the table in Supabase’s SQL editor.');
    }
    const r = await http.call(`https://api.supabase.com/v1/projects/${ref}/database/query`, { method: 'POST',
      headers: { authorization: `Bearer ${secret.accessToken}` }, json: { query: String(query) }, label });
    const data = must(r, label);
    return { rows: Array.isArray(data) ? data.slice(0, 200) : [], count: Array.isArray(data) ? data.length : 0 };
  }
  async function tables() {
    const spec = must(await rest('', { headers: { accept: 'application/openapi+json' } }), label);
    const defs = (spec && spec.definitions) || {};
    const names = Object.keys(defs).filter((n) => IDENT.test(n)).sort().slice(0, 40);
    const counts = await Promise.all(names.slice(0, 15).map((n) => rest(`${n}?select=*&limit=1`, { method: 'HEAD',
      headers: { prefer: 'count=exact' } }).then((r) => Number(String(r.headers.get('content-range') || '')
      .split('/')[1])).catch(() => NaN)));
    return names.map((n, i) => ({ name: n, columns: Object.keys(defs[n].properties || {}),
      rows: Number.isFinite(counts[i]) ? counts[i] : null }));
  }
  async function rows(table, o = {}) {
    const p = [['select', o.columns ? [].concat(o.columns).map((c) => ident(c, 'column')).join(',') : '*'],
      ['limit', String(Math.min(200, Math.max(1, Number(o.limit) || 50)))], ...filters(o.where)];
    if (o.order) p.push(['order', `${ident(String(o.order).replace(/^-/, ''), 'column')}.${/^-/.test(o.order)
      ? 'desc' : 'asc'}`]);
    const data = must(await rest(`${ident(table)}?${qs(p)}`), label);
    return { rows: Array.isArray(data) ? data : [] };
  }
  async function insert(table, list) {
    const data = must(await rest(ident(table), { method: 'POST', json: [].concat(list),
      headers: { prefer: 'return=representation' } }), label);
    return { inserted: Array.isArray(data) ? data.length : 0, rows: Array.isArray(data) ? data.slice(0, 20) : [] };
  }
  async function update(table, where, values) {
    const data = must(await rest(`${ident(table)}?${qs(filters(where))}`, { method: 'PATCH', json: values,
      headers: { prefer: 'return=representation' } }), label);
    return { updated: Array.isArray(data) ? data.length : 0 };
  }
  async function remove(table, where) {
    const data = must(await rest(`${ident(table)}?${qs(filters(where))}`, { method: 'DELETE',
      headers: { prefer: 'return=representation' } }), label);
    return { deleted: Array.isArray(data) ? data.length : 0 };
  }
  const createTable = (name, columns = []) => sql(`create table if not exists public."${ident(name)}" (${
    (columns.length ? columns : [{ name: 'id', identity: true }]).map(column).join(', ')})`);
  const addColumn = (table, c) => sql(`alter table public."${ident(table)}" add column if not exists ${column(c)}`);
  return { label, canSql: Boolean(secret.accessToken), tables, rows, insert, update, remove, sql, createTable,
    addColumn };
}

module.exports = { supabase, filters };
